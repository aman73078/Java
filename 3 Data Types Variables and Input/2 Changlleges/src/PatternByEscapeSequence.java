public class PatternByEscapeSequence{
    static void main() {
//        Right Half Pyramid
        System.out.println("*\n* *\n* * *\n* * * *\n* * * * *");

//        Reverse Right Half Pyramid
        System.out.println("* * * * *\n* * * *\n* * *\n* *\n*");

//        Left Half Pyramid
        System.out.println("        *\n      * *\n    * * *\n  * * * *\n* * * * *");
    }
}